std::string Desc(device *dev, resource res)
{
    if (!res.handle) return "null";
    const resource_desc d = dev->get_resource_desc(res);
    char b[96];
    if (d.type == resource_type::buffer)
        snprintf(b, sizeof(b), "buf %llu", (unsigned long long)d.buffer.size);
    else
        snprintf(b, sizeof(b), "%ux%u f%u%s #%llx", d.texture.width, d.texture.height, (unsigned)d.texture.format,
                 d.texture.depth_or_layers > 1 ? "[]" : "", (unsigned long long)(res.handle & 0xFFFFFF));
    return b;
}

std::string ViewDesc(device *dev, resource_view v) { return v.handle ? Desc(dev, dev->get_resource_from_view(v)) : "null"; }

