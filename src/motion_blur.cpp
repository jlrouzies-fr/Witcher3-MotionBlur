uint64_t UnixMs()
{
    FILETIME ft;
    GetSystemTimeAsFileTime(&ft);
    return ((uint64_t(ft.dwHighDateTime) << 32 | ft.dwLowDateTime) - 116444736000000000ull) / 10000;
}

void LogRaw(const std::string &s)
{
    std::lock_guard lock(g_log_mutex);
    FILE *f = nullptr;
    if (fopen_s(&f, g_log_path, "a") == 0 && f)
    {
        fputs(s.c_str(), f);
        fclose(f);
    }
}

void Log(const char *fmt, ...)
{
    char buf[1024];
    va_list ap;
    va_start(ap, fmt);
    vsnprintf(buf, sizeof(buf), fmt, ap);
    va_end(ap);
    char line[1100];
    snprintf(line, sizeof(line), "[%llu|%llu] %s\n", (unsigned long long)g_frame.load(), (unsigned long long)UnixMs(), buf);
    LogRaw(line);
}

uint32_t Crc32(const void *data, size_t size)
{
    static uint32_t table[256];
    static bool init = false;
    if (!init)
    {
        for (uint32_t i = 0; i < 256; ++i)
        {
            uint32_t c = i;
            for (int k = 0; k < 8; ++k) c = (c & 1) ? 0xEDB88320u ^ (c >> 1) : c >> 1;
            table[i] = c;
        }
        init = true;
    }
    uint32_t crc = 0xFFFFFFFFu;
    const uint8_t *p = static_cast<const uint8_t *>(data);
    for (size_t i = 0; i < size; ++i) crc = table[(crc ^ p[i]) & 0xFF] ^ (crc >> 8);
    return crc ^ 0xFFFFFFFFu;
}

