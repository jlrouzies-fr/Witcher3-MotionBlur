void Begin(command_list *cmd)
{
    CmdState &s = *State(cmd);
    s.lines.clear();
    s.frame = g_frame.load();
    s.tracing = g_trace_frames.count(s.frame) != 0;
    s.ps = s.cs = 0;
    s.rts.clear();
    s.compute_pipe = {0};
    s.compute_is_convert = false;
    s.compute_layout = {0};
    s.compute_tables.clear();
    s.compute_push.clear();
    s.compute_consts.clear();
    s.after_mv = s.mv_found = s.cam_ok = false;
    s.uav_in.clear();
    s.states.clear();
}

void OnInitCommandList(command_list *cmd) { Begin(cmd); }
void OnResetCommandList(command_list *cmd) { Begin(cmd); }
void OnDestroyCommandList(command_list *cmd) { cmd->destroy_private_data<CmdState>(); }

void OnExecuteCommandList(command_queue *, command_list *cmd)
{
    CmdState *s = cmd->get_private_data<CmdState>();
    if (!s || !s->tracing || s->lines.empty()) return;
    std::string out;
    char head[128];
    snprintf(head, sizeof(head), "--- cmdlist %llx recorded frame %llu, executed frame %llu, %zu entries\n",
             (unsigned long long)(uintptr_t)cmd, (unsigned long long)s->frame, (unsigned long long)g_frame.load(), s->lines.size());
    out += head;
    for (const std::string &l : s->lines) out += "  " + l + "\n";
    LogRaw(out);
    s->lines.clear();
}

void OnInitPipeline(device *, pipeline_layout, uint32_t count, const pipeline_subobject *subobjects, pipeline pipe)
{
    for (uint32_t i = 0; i < count; ++i)
    {
        if (subobjects[i].type != pipeline_subobject_type::pixel_shader && subobjects[i].type != pipeline_subobject_type::compute_shader)
            continue;
        const auto *d = static_cast<const shader_desc *>(subobjects[i].data);
        if (!d || !d->code || !d->code_size) continue;
        const uint32_t h = Crc32(d->code, d->code_size);
        std::unique_lock lock(g_pipe_mutex);
        g_pipe_hash[pipe.handle] = h;
        if (subobjects[i].type == pipeline_subobject_type::compute_shader) g_compute_pipes.insert(pipe.handle);
        if (h == kHashConvertMV) Log("ConvertMotionVectors pipeline %016llX", (unsigned long long)pipe.handle);
        return;
    }
}

void OnBindPipeline(command_list *cmd, pipeline_stage stages, pipeline pipe)
{
    CmdState &s = *State(cmd);
    uint32_t h = 0;
    bool compute = false;
    {
        std::shared_lock lock(g_pipe_mutex);
        auto it = g_pipe_hash.find(pipe.handle);
        if (it != g_pipe_hash.end()) h = it->second;
        compute = g_compute_pipes.count(pipe.handle) != 0;
    }
    // D3D12 SetPipelineState arrives as pipeline_stage::all: the shader type recorded at creation decides
    if (compute || stages == pipeline_stage::compute_shader)
    {
        s.cs = h;
        s.compute_pipe = pipe;
        s.compute_is_convert = h == kHashConvertMV;
    }
    else
        s.ps = h;
}

void OnBindRenderTargets(command_list *cmd, uint32_t count, const resource_view *rtvs, resource_view dsv)
{
    CmdState &s = *State(cmd);
    if (!s.tracing) return;
    device *dev = cmd->get_device();
    s.rts.clear();
    for (uint32_t i = 0; i < count; ++i) s.rts += (i ? ", " : "") + ViewDesc(dev, rtvs[i]);
    if (dsv.handle) s.rts += " | ds " + ViewDesc(dev, dsv);
}

bool IsCompute(shader_stage stages) { return (stages & shader_stage::compute) != 0; }

void SwitchLayout(CmdState &s, pipeline_layout layout)
{
    if (layout == s.compute_layout) return;
    s.compute_layout = layout;
    s.compute_tables.clear();
    s.compute_push.clear();
    s.compute_consts.clear();
}

void OnPushDescriptors(command_list *cmd, shader_stage stages, pipeline_layout layout, uint32_t param, const descriptor_table_update &u)
{
    CmdState &s = *State(cmd);
    if (!IsCompute(stages)) return;
    SwitchLayout(s, layout);
    PushedDesc d{u.type, u.binding, u.count, {}, {}};
    if (u.type == descriptor_type::constant_buffer || u.type == descriptor_type::shader_storage_buffer)
        d.ranges.assign(static_cast<const buffer_range *>(u.descriptors), static_cast<const buffer_range *>(u.descriptors) + u.count);
    else if (u.type == descriptor_type::sampler)
        for (uint32_t i = 0; i < u.count; ++i) d.handles.push_back(static_cast<const sampler *>(u.descriptors)[i].handle);
    else if (u.type != descriptor_type::sampler_with_resource_view)
        for (uint32_t i = 0; i < u.count; ++i) d.handles.push_back(static_cast<const resource_view *>(u.descriptors)[i].handle);
    s.compute_push[param] = std::move(d);
}

void OnPushConstants(command_list *cmd, shader_stage stages, pipeline_layout layout, uint32_t param, uint32_t first, uint32_t count, const void *values)
{
    CmdState &s = *State(cmd);
    if (!IsCompute(stages)) return;
    SwitchLayout(s, layout);
    std::vector<uint32_t> &v = s.compute_consts[param];
    if (v.size() < first + count) v.resize(first + count);
    memcpy(v.data() + first, values, count * 4);
}

void OnBindDescriptorTables(command_list *cmd, shader_stage stages, pipeline_layout layout, uint32_t first, uint32_t count,
                            const descriptor_table *tables, uint32_t, const uint32_t *)
{
    CmdState &s = *State(cmd);
    if (s.tracing) Add(s, "tables stage %x first %u count %u", (unsigned)stages, first, count);
    if (count && tables[count - 1].handle) g_game_table = tables[count - 1].handle;
    if (!IsCompute(stages)) return;
    SwitchLayout(s, layout);
    for (uint32_t i = 0; i < count; ++i) s.compute_tables[first + i] = tables[i];
}

// copies this frame's motion vectors and depth into our textures, once both ConvertMotionVectors dispatches are done
// (the game reuses that memory after DLSS, and its own depth copy only exists with its motion blur option on)
void FlushMvCopy(command_list *cmd, CmdState &s)
{
    if (!s.after_mv) return;
    s.after_mv = false;
    if (!s.mv_res) return;
    device *dev = cmd->get_device();
    auto state_of = [&](uint64_t h, resource_usage dflt) {
        auto it = s.states.find(h);
        return it != s.states.end() ? (resource_usage)it->second : dflt;
    };
    const resource mvr = {s.mv_res};
    if (s.conv_depth)
    {
        // motion vectors and depth must belong together (same size): with dynamic resolution the "last r16g16
        // texture" guess can be another buffer; that frame is skipped
        const resource_desc a = dev->get_resource_desc(mvr), b = dev->get_resource_desc(resource{s.conv_depth});
        if (a.texture.depth_or_layers != 1 || a.texture.width != b.texture.width || a.texture.height != b.texture.height)
        {
            static int logged = 0;
            if (logged < 8) { ++logged; Log("skipped frame: motion vectors %ux%u x%u vs depth %ux%u", a.texture.width, a.texture.height, a.texture.depth_or_layers, b.texture.width, b.texture.height); }
            return;
        }
    }
    std::lock_guard lock(g_copy_mutex);
    if (g_mv.exchange(mvr.handle) != mvr.handle) Log("motion vectors: %s", Desc(dev, mvr).c_str());
    const resource_desc mvd = dev->get_resource_desc(mvr);
    if (EnsureCopy(dev, mvd, mvd.texture.format == format::r16g16b16a16_float ? format::r16g16b16a16_float : format::r16g16_float,
                   g_mv_copy, g_mv_copy_srv))
    {
        CopyInto(cmd, mvr, state_of(s.mv_res, resource_usage::unordered_access), g_mv_copy);
        g_mv_frame = g_frame.load();
    }
    if (s.conv_depth)
    {
        const resource dr = {s.conv_depth};
        if (g_depth.exchange(dr.handle) != dr.handle) Log("depth: %s", Desc(dev, dr).c_str());
        if (EnsureCopy(dev, dev->get_resource_desc(dr), format::r32_float_x8_uint, g_depth_copy, g_depth_copy_srv))
        {
            CopyInto(cmd, dr, state_of(dr.handle, resource_usage::depth_stencil_read | resource_usage::shader_resource), g_depth_copy);
            g_depth_frame = g_frame.load();
        }
    }
}

bool OnDraw(command_list *cmd, uint32_t vertices, uint32_t instances, uint32_t, uint32_t)
{
    CmdState &s = *State(cmd);
    FlushMvCopy(cmd, s);
    s.uav_in.clear();
    if (s.tracing) Add(s, "DRAW %u x%u ps %08X -> %s", vertices, instances, s.ps, s.rts.c_str());
    return false;
}

bool OnDrawIndexed(command_list *cmd, uint32_t indices, uint32_t instances, uint32_t, int32_t, uint32_t)
{
    CmdState &s = *State(cmd);
    FlushMvCopy(cmd, s);
    s.uav_in.clear();
    if (s.tracing) Add(s, "DRAWI %u x%u ps %08X -> %s", indices, instances, s.ps, s.rts.c_str());
    return false;
}

bool OnDispatch(command_list *cmd, uint32_t x, uint32_t y, uint32_t z)
{
    CmdState &s = *State(cmd);
    if (s.tracing) Add(s, "DISPATCH %ux%ux%u cs %08X", x, y, z, s.cs);
    if (!s.compute_is_convert) FlushMvCopy(cmd, s);
    if (s.compute_is_convert && ProbeFrame(g_frame.load()))
    {
        const int k = g_probe_k++;
        for (auto &[param, d] : s.compute_push)
        {
            if (d.type != descriptor_type::constant_buffer || d.ranges.empty() || !d.ranges[0].buffer.handle || k >= 4) continue;
            const resource rb = ProbeBuf(cmd->get_device(), g_frame.load());
            if (rb.handle) cmd->copy_buffer_region(d.ranges[0].buffer, d.ranges[0].offset, rb, 128 * k, 80);
            break;
        }
        Log("probe: convert dispatch %d (after_mv %d)", k, (int)s.after_mv);
    }
    if (s.compute_is_convert && !s.after_mv)
    {
        s.after_mv = true;
        s.mv_found = false;
        s.conv_depth = s.depth_res;
        s.mv_res = s.last_rg16;  // candidate; a barrier after the dispatch (two-dispatch frames) overrides it
        // by role: the texture the game moves into UAV for this dispatch, at the size of the depth it reads. With path
        // tracing + ray reconstruction it is r16g16b16a16_float and gets no barrier after the dispatch.
        if (s.depth_res)
        {
            device *dv = cmd->get_device();
            const resource_desc dd = dv->get_resource_desc(resource{s.depth_res});
            for (uint64_t h : s.uav_in)
            {
                const resource_desc d = dv->get_resource_desc(resource{h});
                if (d.type == resource_type::texture_2d && d.texture.depth_or_layers == 1 && d.texture.width == dd.texture.width &&
                    d.texture.height == dd.texture.height &&
                    (d.texture.format == format::r16g16_float || d.texture.format == format::r16g16b16a16_float))
                {
                    s.mv_res = h;
                    s.mv_found = true;
                    break;
                }
            }
        }
        // the reprojection constants (80 bytes, root CBV): the game fills its upload ring after recording, so they are
        // copied on the GPU, in command order, right before this dispatch
        device *dev = cmd->get_device();
        static std::atomic<int> logged{0};
        if (logged++ < 2)
        {
            std::string b;
            for (auto &[param, d] : s.compute_push)
            {
                char t[64];
                snprintf(t, sizeof(t), " push[%u] type %u count %u;", param, (unsigned)d.type, d.count);
                b += t;
            }
            Log("ConvertMotionVectors bindings:%s %zu tables", b.c_str(), s.compute_tables.size());
        }
        s.cam_ok = false;
        for (auto &[param, d] : s.compute_push)
        {
            if (d.type != descriptor_type::constant_buffer || d.ranges.empty() || !d.ranges[0].buffer.handle) continue;
            std::lock_guard lock(g_copy_mutex);
            if (!g_cam_buf.handle &&
                !dev->create_resource(resource_desc(256, memory_heap::default_, resource_usage::constant_buffer | resource_usage::copy_dest),
                                      nullptr, resource_usage::constant_buffer, &g_cam_buf))
            {
                g_cam_buf = {0};
                break;
            }
            cmd->barrier(g_cam_buf, resource_usage::constant_buffer, resource_usage::copy_dest);
            cmd->copy_buffer_region(d.ranges[0].buffer, d.ranges[0].offset, g_cam_buf, 0, 80);
            cmd->barrier(g_cam_buf, resource_usage::copy_dest, resource_usage::constant_buffer);
            s.cam_ok = true;
            break;
        }
        g_cam_ok = s.cam_ok;
    }
    s.uav_in.clear();
    return false;
}

void TryBlurDlssOutput(command_list *cmd, CmdState &s, resource res, resource_usage from, resource_usage to);

void OnBarrier(command_list *cmd, uint32_t count, const resource *res, const resource_usage *from, const resource_usage *to)
{
    CmdState &s = *State(cmd);
    device *dev = cmd->get_device();
    for (uint32_t i = 0; i < count; ++i)
    {
        if (!res[i].handle) continue;
        s.states[res[i].handle] = (uint32_t)to[i];
        if ((to[i] & resource_usage::unordered_access) != 0 && (from[i] & resource_usage::unordered_access) == 0)
            s.uav_in.push_back(res[i].handle);
        if ((to[i] & (resource_usage::shader_resource | resource_usage::depth_stencil_read)) != 0 &&
            (to[i] & resource_usage::depth_stencil_write) == 0)
        {
            const resource_desc d = dev->get_resource_desc(res[i]);
            if (d.type == resource_type::texture_2d && d.texture.format == format::r32_g8_typeless && d.texture.width >= 640) s.depth_res = res[i].handle;
        }
        if (s.after_mv && s.mv_found && res[i].handle == s.mv_res && (to[i] & resource_usage::unordered_access) == 0)
        {
            FlushMvCopy(cmd, s);  // the motion vectors are done (about to be read by DLSS)
            continue;
        }
        {
            const resource_desc d = dev->get_resource_desc(res[i]);
            if (d.type == resource_type::texture_2d && d.texture.format == format::r16g16_float && d.texture.width >= 640 &&
                d.texture.depth_or_layers == 1)
                s.last_rg16 = res[i].handle;
        }
        if (s.after_mv && !s.mv_found)
        {
            const resource_desc d = dev->get_resource_desc(res[i]);
            if (d.type == resource_type::texture_2d && d.texture.format == format::r16g16_float && d.texture.depth_or_layers == 1)
            {
                s.mv_found = true;
                if (g_mv.exchange(res[i].handle) != res[i].handle) Log("motion vectors: %s", Desc(dev, res[i]).c_str());
                s.mv_res = res[i].handle;  // copied with the depth, once both ConvertMotionVectors dispatches are done
            }
        }
        if (s.tracing && dev->get_resource_desc(res[i]).type != resource_type::buffer)
            Add(s, "barrier %s %x -> %x", Desc(dev, res[i]).c_str(), (unsigned)from[i], (unsigned)to[i]);
        if (!s.after_mv) TryBlurDlssOutput(cmd, s, res[i], from[i], to[i]);
    }
}

bool OnClearDepthStencil(command_list *cmd, resource_view dsv, const float *depth, const uint8_t *, uint32_t, const rect *)
{
    if (!depth || !dsv.handle) return false;
    device *dev = cmd->get_device();
    const resource r = dev->get_resource_from_view(dsv);
    if (!r.handle) return false;
    const resource_desc d = dev->get_resource_desc(r);
    if (d.texture.format != format::r32_g8_typeless && d.texture.format != format::d32_float_s8_uint) return false;
    const resource mv = {g_mv.load()};
    if (!mv.handle) return false;
    const resource_desc md = dev->get_resource_desc(mv);
    if (d.texture.width != md.texture.width || d.texture.height != md.texture.height) return false;
    const int rev = *depth < 0.5f ? 1 : 0;
    if (g_reversed_z.exchange(rev) != rev) Log("depth cleared to %g: %s Z", *depth, rev ? "reversed" : "standard");
    return false;
}

