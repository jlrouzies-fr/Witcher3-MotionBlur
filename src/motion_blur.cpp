void Transition(command_list *cmd, CmdState &s, resource r, resource_usage to, std::vector<std::pair<resource, resource_usage>> &undo)
{
    auto it = s.states.find(r.handle);
    const resource_usage from = it != s.states.end() ? (resource_usage)it->second : resource_usage::general;
    if (from == to) return;
    cmd->barrier(r, from, to);
    undo.emplace_back(r, from);
    s.states[r.handle] = (uint32_t)to;
}

void RestoreCompute(command_list *cmd, CmdState &s)
{
    if (s.compute_tables.empty())
    {
        const descriptor_table t = {g_game_table.load()};
        if (t.handle) cmd->bind_descriptor_tables(shader_stage::all_compute, g_res.layout, 1, 1, &t);  // heap only, no dispatch follows
    }
    if (s.compute_pipe.handle) cmd->bind_pipeline(pipeline_stage::all_compute, s.compute_pipe);
    if (!s.compute_layout.handle) return;
    for (auto &[param, t] : s.compute_tables) cmd->bind_descriptor_tables(shader_stage::all_compute, s.compute_layout, param, 1, &t);
    for (auto &[param, d] : s.compute_push)
    {
        descriptor_table_update u = {};
        u.binding = d.binding;
        u.count = d.count;
        u.type = d.type;
        std::vector<resource_view> views;
        std::vector<sampler> samplers;
        if (!d.ranges.empty())
            u.descriptors = d.ranges.data();
        else if (d.type == descriptor_type::sampler)
        {
            for (uint64_t h : d.handles) samplers.push_back({h});
            u.descriptors = samplers.data();
        }
        else
        {
            for (uint64_t h : d.handles) views.push_back({h});
            u.descriptors = views.data();
        }
        cmd->push_descriptors(shader_stage::all_compute, s.compute_layout, param, u);
    }
    for (auto &[param, v] : s.compute_consts)
        cmd->push_constants(shader_stage::all_compute, s.compute_layout, param, 0, (uint32_t)v.size(), v.data());
}

// typed view format for the post-DLSS colour: RGBA16F with RenoDX, the game's own R11G11B10F without it
format ColorViewFormat(format f)
{
    switch (f)
    {
    case format::r16g16b16a16_float:
    case format::r16g16b16a16_typeless: return format::r16g16b16a16_float;
    case format::r11g11b10_float: return format::r11g11b10_float;
    case format::r10g10b10a2_unorm:
    case format::r10g10b10a2_typeless: return format::r10g10b10a2_unorm;
    case format::r8g8b8a8_unorm:
    case format::r8g8b8a8_typeless: return format::r8g8b8a8_unorm;
    default: return format::unknown;
    }
}

bool RunBlur(command_list *cmd, CmdState &s, resource src, resource dst)
{
    device *dev = cmd->get_device();
    const resource mv = g_mv_copy, depth = g_depth_copy;
    if (!mv.handle || !depth.handle || !g_cam_buf.handle) { Reject("no motion vectors, depth or camera constants"); return false; }
    // our pushes switch the root signature and the descriptor heap: the game's compute state (or, without any, a game
    // table for the heap) is rebound afterwards
    if (s.compute_tables.empty() && !g_game_table.load()) { Reject("no game descriptor table seen yet (heap restore)"); return false; }
    const resource_desc md = dev->get_resource_desc(mv), od = dev->get_resource_desc(dst), sd = dev->get_resource_desc(src);
    if ((od.usage & resource_usage::unordered_access) == 0 || (sd.usage & resource_usage::shader_resource) == 0) { Reject("target without UAV or source without SRV usage"); return false; }
    if (g_cfg.mode == 1 && (g_cam_frame != g_frame.load() || !g_cam_buf.handle)) { Reject("objects only, but the camera constants were not found"); return false; }
    const int mode = g_cfg.mode;

    std::lock_guard lock(g_res_mutex);
    if (!EnsureResources(dev, md.texture.width, md.texture.height)) { Reject("resources"); return false; }
    const resource_view color_srv = GetView(dev, src, ColorViewFormat(sd.texture.format), resource_usage::shader_resource);
    const resource_view mv_srv = g_mv_copy_srv, depth_srv = g_depth_copy_srv;
    const resource_view out_uav = GetView(dev, dst, ColorViewFormat(od.texture.format), resource_usage::unordered_access);
    if (!color_srv.handle || !mv_srv.handle || !depth_srv.handle || !out_uav.handle) { Reject("views"); return false; }

    struct Params
    {
        float out_size[2], mv_size[2];
        float shutter, max_len, objects_only, reversed_z, tile, samples, debug, pad;
        float cam[20];
    } p = {};
    static_assert(sizeof(Params) == 32 * 4);
    p.out_size[0] = (float)od.texture.width;
    p.out_size[1] = (float)od.texture.height;
    p.mv_size[0] = (float)md.texture.width;
    p.mv_size[1] = (float)md.texture.height;
    p.shutter = g_cfg.shutter;
    p.max_len = g_cfg.max_len * od.texture.height / 2160.0f;
    p.objects_only = mode == 1 ? 1.0f : 0.0f;
    p.reversed_z = g_reversed_z.load() == 0 ? 0.0f : 1.0f;
    p.tile = (float)g_res.tile;
    p.samples = (float)kSamples[g_cfg.quality];
    p.debug = g_cfg.debug ? 1.0f : 0.0f;
    if (g_cfg.debug && g_test_cycle_ms) p.debug = (float)(1 + (UnixMs() / g_test_cycle_ms / 2) % 4);  // rotate the debug views

    std::vector<std::pair<resource, resource_usage>> undo;
    auto read_state = [&](resource r) {
        auto it = s.states.find(r.handle);
        const resource_usage cur = it != s.states.end() ? (resource_usage)it->second : resource_usage::general;
        // keep a read-only state and add compute read access; anything else becomes a plain compute read
        const bool read_only = cur != resource_usage::general &&
                               (cur & (resource_usage::unordered_access | resource_usage::render_target | resource_usage::copy_dest |
                                       resource_usage::depth_stencil_write)) == 0;
        return read_only ? (cur | resource_usage::shader_resource_non_pixel) : resource_usage::shader_resource_non_pixel;
    };
    Transition(cmd, s, src, read_state(src), undo);
    Transition(cmd, s, dst, resource_usage::unordered_access, undo);

    auto push = [&](pipeline pipe, resource_view t3, resource_view u0, resource_view u1) {
        cmd->bind_pipeline(pipeline_stage::all_compute, pipe);
        cmd->push_constants(shader_stage::all_compute, g_res.layout, 0, 0, 32, &p);
        const resource_view srvs[4] = {color_srv, mv_srv, depth_srv, t3};
        const resource_view uavs[2] = {u0, u1};
        descriptor_table_update us = {};
        us.count = 4;
        us.type = descriptor_type::texture_shader_resource_view;
        us.descriptors = srvs;
        cmd->push_descriptors(shader_stage::all_compute, g_res.layout, 1, us);
        descriptor_table_update uu = {};
        uu.count = 2;
        uu.type = descriptor_type::texture_unordered_access_view;
        uu.descriptors = uavs;
        cmd->push_descriptors(shader_stage::all_compute, g_res.layout, 2, uu);
        const buffer_range cam = {g_cam_buf, 0, 256};
        descriptor_table_update uc = {};
        uc.count = 1;
        uc.type = descriptor_type::constant_buffer;
        uc.descriptors = &cam;
        cmd->push_descriptors(shader_stage::all_compute, g_res.layout, 3, uc);
    };
    // 1: tile max -> tiles_a (tiles_b is bound as the unused t3)
    push(g_res.tilemax, g_res.tiles_b_srv, g_res.dummy_uav, g_res.tiles_a_uav);
    cmd->dispatch((g_res.tiles_w + 7) / 8, (g_res.tiles_h + 7) / 8, 1);
    cmd->barrier(g_res.tiles_a, resource_usage::unordered_access, resource_usage::shader_resource_non_pixel);
    // 2: neighbour max -> tiles_b
    push(g_res.neighbormax, g_res.tiles_a_srv, g_res.dummy_uav, g_res.tiles_b_uav);
    cmd->dispatch((g_res.tiles_w + 7) / 8, (g_res.tiles_h + 7) / 8, 1);
    cmd->barrier(g_res.tiles_b, resource_usage::unordered_access, resource_usage::shader_resource_non_pixel);
    // 3: gather into the game's post-process texture
    push(g_res.gather, g_res.tiles_b_srv, out_uav, g_res.dummy_uav);
    cmd->dispatch((od.texture.width + 7) / 8, (od.texture.height + 7) / 8, 1);
    cmd->barrier(g_res.tiles_a, resource_usage::shader_resource_non_pixel, resource_usage::unordered_access);
    cmd->barrier(g_res.tiles_b, resource_usage::shader_resource_non_pixel, resource_usage::unordered_access);

    for (auto it = undo.rbegin(); it != undo.rend(); ++it)
    {
        cmd->barrier(it->first, (resource_usage)s.states[it->first.handle], it->second);
        s.states[it->first.handle] = (uint32_t)it->second;
    }
    if (ProbeFrame(g_frame.load()))
    {
        const resource rb = ProbeBuf(dev, g_frame.load());
        if (rb.handle)
        {
            cmd->copy_buffer_region(g_cam_buf, 0, rb, 3 * 128, 80);  // what the blur used (slot 3)
            const subresource_box box = {0, (int32_t)md.texture.height / 2, 0, 1920, (int32_t)md.texture.height / 2 + 1, 1};
            int slot = 0;
            for (resource t : {mv, depth})
            {
                cmd->barrier(t, resource_usage::shader_resource, resource_usage::copy_source);
                cmd->copy_texture_to_buffer(t, 0, &box, rb, kProbeRow + slot * 1920 * 4, 1920, 1);
                cmd->barrier(t, resource_usage::copy_source, resource_usage::shader_resource);
                ++slot;
            }
        }
    }
    RestoreCompute(cmd, s);
    return true;
}

bool ActiveNow()
{
    if (!g_cfg.enabled) return false;
    if (g_test_cycle_ms) return (UnixMs() / g_test_cycle_ms) % 2 == 1;
    return true;
}

bool HandleCopy(command_list *cmd, resource src, resource dst)
{
    CmdState &s = *State(cmd);
    device *dev = cmd->get_device();
    const resource_desc sd = dev->get_resource_desc(src), dd = dev->get_resource_desc(dst);
    if (sd.type != resource_type::texture_2d || dd.type != resource_type::texture_2d) return false;
    // the game's depth copy right after ConvertMotionVectors (with its motion blur option on or off) reads the depth
    if (s.after_mv && sd.texture.format == format::r32_g8_typeless && sd.texture.width >= 640) s.conv_depth = src.handle;
    FlushMvCopy(cmd, s);
    return false;
}

// The DLSS output, right when DLSS is done writing it (it leaves UAV state), before any post-process or UI pass reads
// it: the blur runs in place (DLSS output -> our copy -> gather back into the DLSS output). With RenoDX in SDR the game
// then copies it into its post-process texture; in HDR (and without RenoDX) the post passes read it directly, and the
// only full-size copy left comes after the HUD was composited in.
void TryBlurDlssOutput(command_list *cmd, CmdState &s, resource res, resource_usage from, resource_usage to)
{
    if ((from & resource_usage::unordered_access) == 0 || (to & resource_usage::unordered_access) != 0) return;
    const uint64_t frame = g_frame.load();
    if (g_last_injected_frame == (uint32_t)frame || !g_mv_copy.handle || g_mv_frame != frame) return;
    device *dev = cmd->get_device();
    const resource_desc d = dev->get_resource_desc(res);
    if (d.type != resource_type::texture_2d || d.texture.samples > 1) return;
    const resource_desc md = dev->get_resource_desc(g_mv_copy);
    if (d.texture.width <= md.texture.width || d.texture.height <= md.texture.height) return;  // not upscaled
    // the DLSS output has the size of the screen: with dynamic resolution other render-size textures pass the test above
    if (d.texture.width != g_bb_w || d.texture.height != g_bb_h)
    {
        static int logged = 0;
        if (logged < 8 && d.texture.width >= 1280) { ++logged; Log("skipped %ux%u texture (back buffer %ux%u)", d.texture.width, d.texture.height, g_bb_w.load(), g_bb_h.load()); }
        return;
    }
    if (ColorViewFormat(d.texture.format) == format::unknown)
    {
        static std::set<uint32_t> seen;
        if (seen.insert((uint32_t)d.texture.format).second && seen.size() <= 8)
            Log("skipped upscaled UAV texture (unsupported format): %s", Desc(dev, res).c_str());
        return;
    }
    // With path tracing + ray reconstruction, temporal-history textures (two of each, swapped every frame) leave UAV
    // state before the DLSS output: the output is the first one that is the same texture as last frame.
    {
        static std::mutex m;
        static std::unordered_set<uint64_t> cur, prev;
        static uint64_t cur_frame = ~0ull;
        std::lock_guard lock(m);
        if (cur_frame != frame)
        {
            if (cur_frame + 1 == frame) prev = std::move(cur);
            else prev.clear();
            cur.clear();
            cur_frame = frame;
        }
        cur.insert(res.handle);
        if (!prev.count(res.handle)) return;
    }
    if (g_depth_frame != frame) { Reject("DLSS output without this frame's depth"); return; }
    static bool logged = false;
    if (!logged) { logged = true; Log("DLSS output found: %s (%x -> %x)", Desc(dev, res).c_str(), (unsigned)from, (unsigned)to); }
    if (!ActiveNow()) { g_last_injected_frame = (uint32_t)frame; return; }
    if ((d.usage & resource_usage::unordered_access) == 0) { Reject("DLSS output without UAV usage"); return; }
    {
        std::lock_guard lock(g_copy_mutex);
        if (!EnsureCopy(dev, d, ColorViewFormat(d.texture.format), g_color_copy, g_color_copy_srv)) { Reject("colour copy"); return; }
        CopyInto(cmd, res, to, g_color_copy);
    }
    s.states[g_color_copy.handle] = (uint32_t)resource_usage::shader_resource;
    if (!RunBlur(cmd, s, g_color_copy, res)) return;
    if (g_last_injected_frame.exchange((uint32_t)frame) != (uint32_t)frame && g_injected_frames++ == 0) Log("first blurred frame");
}

bool OnCopyTextureRegion(command_list *cmd, resource src, uint32_t ss, const subresource_box *sb, resource dst, uint32_t ds,
                         const subresource_box *db, filter_mode)
{
    CmdState &s = *State(cmd);
    if (s.tracing) Add(s, "copy %s -> %s", Desc(cmd->get_device(), src).c_str(), Desc(cmd->get_device(), dst).c_str());
    if (ss != 0 || ds != 0) return false;
    // a whole-texture copy: no source box (or one at the origin), destination at the origin
    if (sb && (sb->left != 0 || sb->top != 0 || sb->front != 0)) return false;
    if (db && (db->left != 0 || db->top != 0 || db->front != 0)) return false;
    return HandleCopy(cmd, src, dst);
}

bool OnCopyResource(command_list *cmd, resource src, resource dst)
{
    CmdState &s = *State(cmd);
    if (s.tracing) Add(s, "copyres %s -> %s", Desc(cmd->get_device(), src).c_str(), Desc(cmd->get_device(), dst).c_str());
    return HandleCopy(cmd, src, dst);
}

uint32_t g_logged_active = 2;

void OnPresent(command_queue *queue, swapchain *sc, const rect *, const rect *, uint32_t, const rect *)
{
    const uint64_t f = ++g_frame;
    if (sc)
    {
        const resource bb = sc->get_current_back_buffer();
        if (bb.handle)
        {
            const resource_desc bd = queue->get_device()->get_resource_desc(bb);
            g_bb_w = bd.texture.width;
            g_bb_h = bd.texture.height;
        }
    }
    DestroyRetired(queue->get_device(), false);
    if (g_probe && f % 15 == 0)
    {
        g_probe_k = 0;
        const uint64_t old = f - 30;
        resource &r = g_probe_rb[(old / 15) % 4];
        void *data = nullptr;
        device *dev = queue->get_device();
        if (r.handle && dev->map_buffer_region(r, 0, kProbeSize, map_access::read_only, &data))
        {
            const float *cb = (const float *)data;
            const uint32_t *mvh = (const uint32_t *)((const char *)data + kProbeRow);
            const float *dep = (const float *)((const char *)data + kProbeRow + 1920 * 4);
            std::string t;
            char b[256];
            for (int k = 0; k < 4; ++k)
            {
                const float *c = cb + 32 * k;
                snprintf(b, sizeof(b), "\n  cb%d: %g %g %g %g | %g %g %g %g | %g %g %g %g | %g %g %g %g | %g %g %g %g", k, c[0], c[1], c[2], c[3], c[4],
                         c[5], c[6], c[7], c[8], c[9], c[10], c[11], c[12], c[13], c[14], c[15], c[16], c[17], c[18], c[19]);
                t += b;
            }
            auto h2f = [](uint16_t h) {
                const uint32_t e = (h >> 10) & 31, m = h & 1023;
                float v = e == 0 ? m / 1024.0f / 16384.0f : e == 31 ? INFINITY : (1 + m / 1024.0f) * powf(2.0f, (float)e - 15);
                return (h & 0x8000) ? -v : v;
            };
            for (int x = 0; x < 1920; x += 160)
            {
                const float mx = h2f(mvh[x] & 0xffff), my = h2f(mvh[x] >> 16), d = dep[x];
                std::string cs;
                for (int k : {0, 1, 3})
                {
                    const float *c = cb + 32 * k;
                    const float u = (x + 0.5f) * c[2], v = 540.5f * c[3], nx = 2 * u - 1, ny = 1 - 2 * v;
                    const float cx = c[4] * nx + c[8] * ny + c[12] * d + c[16], cy = c[5] * nx + c[9] * ny + c[13] * d + c[17],
                                cw = c[7] * nx + c[11] * ny + c[15] * d + c[19];
                    snprintf(b, sizeof(b), " c%d %.5f %.5f", k, 0.5f * cx / cw + 0.5f - u, -0.5f * cy / cw + 0.5f - v);
                    cs += b;
                }
                snprintf(b, sizeof(b), "\n  x %4d d %.6g mv %.5f %.5f |%s", x, d, mx, my, cs.c_str());
                t += b;
            }
            dev->unmap_buffer_region(r);
            Log("probe frame %llu:%s", (unsigned long long)old, t.c_str());
        }
    }
    if (g_trace_frames.count(f)) Log("===== trace frame %llu starts", (unsigned long long)f);
    if (g_test_cycle_ms)
    {
        const uint32_t a = ActiveNow() ? 1 : 0;
        if (a != g_logged_active)
        {
            g_logged_active = a;
            const uint64_t now = UnixMs();
            Log("blur %s at unix ms %llu (debug view %llu)", a ? "on" : "off", (unsigned long long)now,
                (unsigned long long)(g_cfg.debug ? 1 + (now / g_test_cycle_ms / 2) % 4 : 0));
        }
    }
    if (f % 1800 == 0) Log("frames with blur so far: %u", g_injected_frames.load());
}

void OnDestroyDevice(device *dev)
{
    DestroyRetired(dev, true);
    std::lock_guard lock(g_res_mutex);
    for (auto &[k, v] : g_res.views)
        if (v.handle) dev->destroy_resource_view(v);
    g_views_of.clear();
    DestroyTiles(dev, true);
    if (g_res.dummy_uav.handle) dev->destroy_resource_view(g_res.dummy_uav);
    if (g_res.dummy.handle) dev->destroy_resource(g_res.dummy);
    for (pipeline *pp : {&g_res.tilemax, &g_res.neighbormax, &g_res.gather})
        if (pp->handle) dev->destroy_pipeline(*pp);
    if (g_res.layout.handle) dev->destroy_pipeline_layout(g_res.layout);
    {
        std::lock_guard l2(g_copy_mutex);
        for (resource_view *v : {&g_mv_copy_srv, &g_depth_copy_srv, &g_color_copy_srv})
            if (v->handle) { dev->destroy_resource_view(*v); *v = {0}; }
        for (resource *r : {&g_mv_copy, &g_depth_copy, &g_color_copy})
            if (r->handle) { dev->destroy_resource(*r); *r = {0}; }
        if (g_cam_buf.handle) { dev->destroy_resource(g_cam_buf); g_cam_buf = {0}; }
        for (resource &r : g_probe_rb)
            if (r.handle) { dev->destroy_resource(r); r = {0}; }
    }
    g_res = Resources();
}

