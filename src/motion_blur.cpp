// Object Motion Blur - ReShade add-on for The Witcher 3 5.0 (DX12).
//
// The game's own motion blur is camera-only (reprojection from depth, shader 0xD1915481). But for DLSS the game also
// builds full per-pixel motion vectors, object motion included (ConvertMotionVectors, compute 0x9F1C32F1, writes an
// r16g16_float texture at render resolution). This add-on reuses them for a real per-object motion blur:
//   * after the 0x9F1C32F1 dispatch it remembers the motion-vector texture (first r16g16_float barrier) and that
//     dispatch's constant buffer (previous-frame reprojection, to remove the camera motion in "objects only" mode),
//   * it remembers the depth copy the game makes right after (r32_g8 texture copy at render resolution),
//   * the game then copies the 4K DLSS output into its post-process texture (r16g16b16a16_float). The add-on replaces
//     that copy with its three compute passes (shaders/omb.hlsl), so the blurred image lands where the copy would have:
//     linear HDR, before bloom, tonemapping and the UI.
// Afterwards the game's compute pipeline, root signature, descriptor tables and root constants are put back.
//
// MB_TRACE_FRAMES="600,1800" (environment) writes those frames' command lists to ObjectMotionBlur.log.
// Shader hashes are CRC32 of the whole DXBC container (RenoDX scheme).

