// Textures replaced on a resolution change are destroyed a few frames later: command lists still in flight on the GPU
// may read them (destroying them at once hung the GPU right after the game's dynamic resolution changed).
struct Retired { uint64_t frame; resource_view view; resource res; };
std::mutex g_retire_mutex;
std::vector<Retired> g_retired;
void Retire(resource_view v, resource r)
{
    std::lock_guard lock(g_retire_mutex);
    g_retired.push_back({g_frame.load(), v, r});
}
void DestroyRetired(device *dev, bool all)
{
    std::vector<Retired> due;
    {
        std::lock_guard lock(g_retire_mutex);
        for (size_t i = 0; i < g_retired.size();)
        {
            if (!all && g_frame.load() < g_retired[i].frame + 8) { ++i; continue; }
            due.push_back(g_retired[i]);
            g_retired.erase(g_retired.begin() + i);
        }
    }
    for (const Retired &r : due)  // outside any lock of ours: destroying raises events
    {
        if (r.view.handle) dev->destroy_resource_view(r.view);
        if (r.res.handle) dev->destroy_resource(r.res);
    }
}

// (re)creates one of our copies to match the game's texture; it is kept in shader_resource state between uses
bool EnsureCopy(device *dev, const resource_desc &game, format view_fmt, resource &copy, resource_view &srv)
{
    if (copy.handle)
    {
        const resource_desc d = dev->get_resource_desc(copy);
        if (d.texture.width == game.texture.width && d.texture.height == game.texture.height && d.texture.format == game.texture.format)
            return true;
        Retire(srv, copy);
        copy = {0};
        srv = {0};
    }
    resource_desc d(game.texture.width, game.texture.height, 1, 1, game.texture.format, 1, memory_heap::default_,
                    resource_usage::shader_resource | resource_usage::copy_dest);
    if (!dev->create_resource(d, nullptr, resource_usage::shader_resource, &copy)) { copy = {0}; return false; }
    if (!dev->create_resource_view(copy, resource_usage::shader_resource, resource_view_desc(view_fmt), &srv))
    {
        dev->destroy_resource(copy);
        copy = {0};
        srv = {0};
        return false;
    }
    return true;
}

void CopyInto(command_list *cmd, resource game, resource_usage game_state, resource copy)
{
    if (game_state == resource_usage::unordered_access) cmd->barrier(game, resource_usage::unordered_access, resource_usage::unordered_access);
    const bool move = (game_state & resource_usage::copy_source) == 0;
    if (move) cmd->barrier(game, game_state, resource_usage::copy_source);
    cmd->barrier(copy, resource_usage::shader_resource, resource_usage::copy_dest);
    cmd->copy_resource(game, copy);
    cmd->barrier(copy, resource_usage::copy_dest, resource_usage::shader_resource);
    if (move) cmd->barrier(game, resource_usage::copy_source, game_state);
}
