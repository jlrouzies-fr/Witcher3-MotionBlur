struct Resources
{
    bool failed = false;
    pipeline_layout layout = {0};
    pipeline tilemax = {0}, neighbormax = {0}, gather = {0};
    resource tiles_a = {0}, tiles_b = {0}, dummy = {0};
    resource_view tiles_a_srv = {0}, tiles_a_uav = {0}, tiles_b_srv = {0}, tiles_b_uav = {0}, dummy_uav = {0};
    uint32_t tiles_w = 0, tiles_h = 0, tile = 0;
    std::unordered_map<uint64_t, resource_view> views;  // (resource, format, usage) -> view
};
Resources g_res;
std::mutex g_res_mutex;
std::unordered_map<uint64_t, std::vector<uint64_t>> g_views_of;  // resource -> keys in g_res.views

resource_view GetView(device *dev, resource res, format fmt, resource_usage usage)
{
    const uint64_t key = res.handle * 0x9E3779B97F4A7C15ull ^ (uint64_t)fmt << 8 ^ (uint64_t)usage;
    auto it = g_res.views.find(key);
    if (it != g_res.views.end()) return it->second;
    resource_view v = {0};
    if (!dev->create_resource_view(res, usage, resource_view_desc(fmt), &v)) v = {0};
    g_res.views[key] = v;
    g_views_of[res.handle].push_back(key);
    return v;
}

void OnDestroyResource(device *dev, resource res)
{
    if (res.handle == g_mv) g_mv = 0;
    if (res.handle == g_depth) g_depth = 0;
    std::lock_guard lock(g_res_mutex);
    auto it = g_views_of.find(res.handle);
    if (it == g_views_of.end()) return;
    for (uint64_t key : it->second)
    {
        auto v = g_res.views.find(key);
        if (v == g_res.views.end()) continue;
        if (v->second.handle) dev->destroy_resource_view(v->second);
        g_res.views.erase(v);
    }
    g_views_of.erase(it);
}

void DestroyTiles(device *dev, bool now)
{
    for (resource_view *v : {&g_res.tiles_a_srv, &g_res.tiles_a_uav, &g_res.tiles_b_srv, &g_res.tiles_b_uav})
        if (v->handle) { if (now) dev->destroy_resource_view(*v); else Retire(*v, {0}); *v = {0}; }
    for (resource *r : {&g_res.tiles_a, &g_res.tiles_b})
        if (r->handle) { if (now) dev->destroy_resource(*r); else Retire({0}, *r); *r = {0}; }
}

bool EnsureResources(device *dev, uint32_t mv_w, uint32_t mv_h)
{
    if (g_res.failed) return false;
    if (!g_res.layout.handle)
    {
        const pipeline_layout_param params[4] = {
            pipeline_layout_param(constant_range{0, 0, 0, 32, shader_stage::all_compute}),
            pipeline_layout_param(descriptor_range{0, 0, 0, 4, shader_stage::all_compute, 1, descriptor_type::texture_shader_resource_view}),
            pipeline_layout_param(descriptor_range{0, 0, 0, 2, shader_stage::all_compute, 1, descriptor_type::texture_unordered_access_view}),
            pipeline_layout_param(descriptor_range{0, 1, 0, 1, shader_stage::all_compute, 1, descriptor_type::constant_buffer}),
        };
        if (!dev->create_pipeline_layout(4, params, &g_res.layout))
        {
            Log("create_pipeline_layout failed");
            g_res.failed = true;
            return false;
        }
        struct { const void *code; size_t size; pipeline *out; const char *name; } cs[] = {
            {g_cs_TileMax, sizeof(g_cs_TileMax), &g_res.tilemax, "tilemax"},
            {g_cs_NeighborMax, sizeof(g_cs_NeighborMax), &g_res.neighbormax, "neighbormax"},
            {g_cs_Gather, sizeof(g_cs_Gather), &g_res.gather, "gather"},
        };
        for (auto &c : cs)
        {
            shader_desc sd = {};
            sd.code = c.code;
            sd.code_size = c.size;
            pipeline_subobject so = {pipeline_subobject_type::compute_shader, 1, &sd};
            if (!dev->create_pipeline(g_res.layout, 1, &so, c.out))
            {
                Log("create_pipeline %s failed", c.name);
                g_res.failed = true;
                return false;
            }
        }
        if (!dev->create_resource(resource_desc(1, 1, 1, 1, format::r16g16b16a16_float, 1, memory_heap::default_, resource_usage::unordered_access),
                                  nullptr, resource_usage::unordered_access, &g_res.dummy) ||
            !dev->create_resource_view(g_res.dummy, resource_usage::unordered_access, resource_view_desc(format::r16g16b16a16_float), &g_res.dummy_uav))
        {
            Log("dummy texture failed");
            g_res.failed = true;
            return false;
        }
        Log("pipelines ready");
    }
    const uint32_t tile = 20;
    const uint32_t tw = (mv_w + tile - 1) / tile, th = (mv_h + tile - 1) / tile;
    if (g_res.tiles_a.handle && g_res.tiles_w == tw && g_res.tiles_h == th) return true;
    DestroyTiles(dev, false);
    const resource_desc td(tw, th, 1, 1, format::r16g16_float, 1, memory_heap::default_,
                           resource_usage::shader_resource | resource_usage::unordered_access);
    for (auto [r, srv, uav] : {std::tuple{&g_res.tiles_a, &g_res.tiles_a_srv, &g_res.tiles_a_uav},
                               std::tuple{&g_res.tiles_b, &g_res.tiles_b_srv, &g_res.tiles_b_uav}})
    {
        if (!dev->create_resource(td, nullptr, resource_usage::unordered_access, r) ||
            !dev->create_resource_view(*r, resource_usage::shader_resource, resource_view_desc(format::r16g16_float), srv) ||
            !dev->create_resource_view(*r, resource_usage::unordered_access, resource_view_desc(format::r16g16_float), uav))
        {
            Log("tile textures failed");
            g_res.failed = true;
            return false;
        }
    }
    g_res.tiles_w = tw;
    g_res.tiles_h = th;
    g_res.tile = tile;
    Log("tile textures %ux%u (tile %u px, motion vectors %ux%u)", tw, th, tile, mv_w, mv_h);
    return true;
}

