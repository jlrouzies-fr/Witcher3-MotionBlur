void DrawOverlay(effect_runtime *)
{
    bool dirty = false;
    if (ImGui::Checkbox("Enabled", &g_cfg.enabled)) dirty = true;
    ImGui::BeginDisabled(!g_cfg.enabled);
    if (ImGui::SliderFloat("Shutter", &g_cfg.shutter, 0.1f, 1.0f, "%.2f frame")) dirty = true;
    if (ImGui::SliderFloat("Max length", &g_cfg.max_len, 16.0f, 192.0f, "%.0f px (4K)")) dirty = true;
    if (ImGui::Combo("Quality", &g_cfg.quality, kQualityNames, 3)) dirty = true;
    ImGui::Checkbox("Debug view (blur vectors as colours)", &g_cfg.debug);
    ImGui::EndDisabled();
    ImGui::TextWrapped("Per-pixel motion blur from the game's DLSS motion vectors: characters, horses, weapons and creatures "
                       "blur with their own motion, and with the camera's. Turn the game's own Motion Blur option off to avoid "
                       "blurring camera turns twice. Shutter 0.5 = 180 degrees, like film.");
    ImGui::Separator();
    ImGui::Text("Motion vectors: %s. Depth: %s (%s Z). Frames blurred: %u", g_mv ? "found" : "not found yet",
                g_depth ? "found" : "not found yet", g_reversed_z == 1 ? "reversed" : g_reversed_z == 0 ? "standard" : "unknown",
                g_injected_frames.load());
    if (dirty) SaveConfig();
}
